// Build-time asset refresh, not a runtime network dependency.
const fs = require('node:fs');
const providers = ['gmail','slack','googlecalendar','notion','instagram','reddit','github','twitter','trello','jira'];
(async () => {
  const logos = {};
  for (const slug of providers) {
    const source = slug === 'twitter' ? 'https://raw.githubusercontent.com/simple-icons/simple-icons/develop/icons/x.svg' : `https://logos.composio.dev/api/${slug}`;
    const response = await fetch(source, { signal: AbortSignal.timeout(20000) });
    if (!response.ok) throw new Error(`Logo download failed for ${slug}`);
    const svg = await response.text();
    if (!svg.includes('<svg') || /<script|<foreignObject|\bon\w+=|(?:href|src)\s*=\s*["']https?:/i.test(svg)) throw new Error(`Unsupported SVG in ${slug}`);
    logos[slug] = svg;
  }
  fs.writeFileSync('src/constants/providerLogos.ts', '// Provider SVGs from verified Composio toolkit metadata; X from Simple Icons (CC0).\n// See assets/providers/ATTRIBUTION.md. Generated by scripts/fetch-provider-logos.cjs.\nexport const providerLogos = '+JSON.stringify(logos,null,2)+' as const;\n');
  console.log(JSON.stringify({ status: 'PASS', providerLogos: Object.keys(logos), runtimeDownloads: false }));
})().catch(error => { console.error(error.message); process.exitCode = 1; });
